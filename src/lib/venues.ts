export function getVenue(slug: string) {
  return VENUES.find((venue) => venue.slug === slug);
}

export function venueScene(venue: Venue): VenueScene {
  return venue.scene ?? "gypsy";
}

const SCENE_RANK: Record<VenueScene, number> = { gypsy: 0, jazz: 1, world: 2 };

export function sortVenues(venues: Venue[]) {
  return [...venues].sort(
    (a, b) =>
      SCENE_RANK[venueScene(a)] - SCENE_RANK[venueScene(b)] ||
      a.city.localeCompare(b.city) ||
      a.name.localeCompare(b.name),
  );
}

export function venuesByCountry(extra: Venue[] = []) {
  const all = [...VENUES];
  for (const venue of extra) {
    if (!all.some((row) => row.slug === venue.slug)) all.push(venue);
  }
  const counts: Record<string, number> = {};
  for (const venue of all) counts[venue.country] = (counts[venue.country] ?? 0) + 1;
  const present = [...new Set(all.map((venue) => venue.country))];
  const lead = ["Netherlands", "Germany", "France", "Belgium"].filter((name) =>
    present.includes(name),
  );
  const rest = present
    .filter((name) => !lead.includes(name))
    .sort((a, b) => (counts[b] ?? 0) - (counts[a] ?? 0) || a.localeCompare(b));
  return [...lead, ...rest].map((country) => ({
    country,
    venues: sortVenues(all.filter((venue) => venue.country === country)),
  }));
}
