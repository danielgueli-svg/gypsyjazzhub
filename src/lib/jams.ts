export function jamTimeZone(jam: { country: string; city: string }) {
  const city = jam.city.trim().toLowerCase();
  if (city && CITY_TZ[city]) return CITY_TZ[city];
  return COUNTRY_TZ[jam.country] ?? "UTC";
}

function ymdInTimeZone(date: Date, timeZone: string) {
  return new Intl.DateTimeFormat("en-CA", {
    timeZone,
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).format(date);
}

function addCalendarDays(ymd: string, days: number) {
  const [year, month, day] = ymd.split("-").map(Number);
  const next = new Date(Date.UTC(year, month - 1, day + days));
  return next.toISOString().slice(0, 10);
}

/** Split by the jam's own local calendar — not the visitor's clock. */
export function splitUpcomingJams(jams: Jam[], now = new Date()) {
  const today: Jam[] = [];
  const week: Jam[] = [];
  const later: Jam[] = [];
  for (const jam of jams) {
    const tz = jamTimeZone(jam);
    const jamDay = ymdInTimeZone(new Date(jam.nextStartsAt), tz);
    const todayDay = ymdInTimeZone(now, tz);
    if (Number.isNaN(new Date(jam.nextStartsAt).getTime())) continue;
    if (jamDay === todayDay) today.push(jam);
    else if (jamDay > todayDay && jamDay <= addCalendarDays(todayDay, 7)) week.push(jam);
    else later.push(jam);
  }
  return { today, week, later };
}

export function formatJamNext(jam: Jam) {
  const date = new Date(jam.nextStartsAt);
  if (Number.isNaN(date.getTime())) return jam.nextStartsAt;
  const parts = new Intl.DateTimeFormat("en-GB", {
    timeZone: jamTimeZone(jam),
    weekday: "short",
    day: "numeric",
    month: "short",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit",
    hour12: false,
  }).formatToParts(date);
  const get = (type: Intl.DateTimeFormatPartTypes) =>
    parts.find((part) => part.type === type)?.value ?? "";
  const hour = get("hour").padStart(2, "0");
  const minute = get("minute").padStart(2, "0");
  return `${get("weekday")} ${get("day")} ${get("month")} ${get("year")} · ${hour}:${minute}`;
}

