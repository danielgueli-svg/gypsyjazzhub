export function getJam(slug: string) {
  return JAMS.find((jam) => jam.slug === slug);
}

function isPostedNotRecurring(when: string) {
  return /when posted|no regular|festival week|camp week|selected friday|check (the band|facebook|kozlov)/i.test(
    when,
  );
}

function isWeekly(when: string) {
  return /weekly|every (monday|tuesday|wednesday|thursday|friday|saturday|sunday)|weekends|mondays|tuesdays|wednesdays|thursdays|fridays|saturdays|sundays/i.test(
    when,
  ) && !/every other|biweekly|1st|2nd|3rd|4th|first |last /i.test(when);
}

function isBiweekly(when: string) {
  return /every other|biweekly|every other tuesday/i.test(when);
}

function isMonthlyish(when: string) {
  return /monthly|1st |2nd |3rd |4th |first |last /i.test(when);
}

/** Keep the original clock; only walk the calendar forward. Do not invent new rooms. */
export function rollJamNext(jam: Jam, now = Date.now()): string {
  const raw = jam.nextStartsAt;
  const date = new Date(raw);
  if (Number.isNaN(date.getTime()) || date.getTime() >= now) return raw;
  if (isPostedNotRecurring(jam.when)) return raw;
  const stepDays = isWeekly(jam.when) ? 7 : isBiweekly(jam.when) ? 14 : isMonthlyish(jam.when) ? 28 : 0;
  if (!stepDays) return raw;
  let guard = 0;
  while (date.getTime() < now && guard < 80) {
    date.setUTCDate(date.getUTCDate() + stepDays);
    guard += 1;
  }
  return date.toISOString();
}

export function upcomingJams(now = Date.now()) {
  return JAMS.map((jam) => ({ ...jam, nextStartsAt: rollJamNext(jam, now) }))
    .filter((jam) => new Date(jam.nextStartsAt).getTime() >= now)
    .sort((a, b) => new Date(a.nextStartsAt).getTime() - new Date(b.nextStartsAt).getTime());
}

export function jamsByCountry(extra: Jam[] = [], now = Date.now()) {
  const all = [...upcomingJams(now)];
  for (const jam of extra) {
    if (new Date(jam.nextStartsAt).getTime() < now) continue;
    if (!all.some((row) => row.slug === jam.slug)) all.push(jam);
  }
  const counts: Record<string, number> = {};
  for (const jam of all) counts[jam.country] = (counts[jam.country] ?? 0) + 1;
  const present = [...new Set(all.map((jam) => jam.country))];
  const ordered = present.sort(
    (a, b) => (counts[b] ?? 0) - (counts[a] ?? 0) || a.localeCompare(b),
  );
  return ordered.map((country) => ({
    country,
    jams: all
      .filter((jam) => jam.country === country)
      .sort((a, b) => {
        const meetup = Number((b.kind ?? "regular") === "meetup") - Number((a.kind ?? "regular") === "meetup");
        if (meetup) return meetup;
        return new Date(a.nextStartsAt).getTime() - new Date(b.nextStartsAt).getTime();
      }),
  }));
}

export function jamsInCountry(atlasName: string, now = Date.now()) {
  return upcomingJams(now).filter((jam) => jam.country === atlasName);
}
