export const LUTHIERS: Luthier[] = [
  ...GUITAR_LUTHIERS,
  ...BASS_LUTHIERS.map((row) => ({
    ...row,
    note: BASS_NOTES[row.slug] ?? row.note,
  })),
  ...VIOLIN_LUTHIERS,
];

export function getLuthier(slug: string) {
  return LUTHIERS.find((row) => row.slug === slug);
}

export function splitLuthiers(rows: Luthier[]) {
  return {
    guitar: rows.filter((row) => row.craft === "guitar"),
    bass: rows.filter((row) => row.craft === "bass"),
    violin: rows.filter((row) => row.craft === "violin"),
  };
}

export function luthiersByCountry(extra: Luthier[] = []) {
  const all = [...LUTHIERS];
  for (const row of extra) {
    if (!all.some((item) => item.slug === row.slug)) all.push(row);
  }
  const counts: Record<string, number> = {};
  for (const row of all) counts[row.country] = (counts[row.country] ?? 0) + 1;
  const present = [...new Set(all.map((row) => row.country))];
  const lead = ["Italy", "France"].filter((name) => present.includes(name));
  const rest = present
    .filter((name) => !lead.includes(name))
    .sort((a, b) => (counts[b] ?? 0) - (counts[a] ?? 0) || a.localeCompare(b));
  return [...lead, ...rest].map((country) => ({
    country,
    luthiers: all
      .filter((row) => row.country === country)
      .sort((a, b) => a.name.localeCompare(b.name)),
  }));
}

export function luthiersByCountryForCraft(craft: LuthierCraft, extra: Luthier[] = []) {
  return luthiersByCountry(extra)
    .map((group) => ({
      ...group,
      luthiers: group.luthiers.filter((row) => row.craft === craft),
    }))
    .filter((group) => group.luthiers.length);
}

export function bassLuthiersByCountry(extra: Luthier[] = []) {
  return luthiersByCountryForCraft("bass", extra);
}

export function violinLuthiersByCountry(extra: Luthier[] = []) {
  return luthiersByCountryForCraft("violin", extra);
}

export function siteHost(url: string) {
  if (!url.trim()) return "";
  try {
    return new URL(url).host.replace(/^www\./, "");
  } catch {
    return url.replace(/^https?:\/\/(www\.)?/i, "").replace(/\/.*$/, "");
  }
}
