export type LuthierCraft = "guitar" | "bass" | "violin";

export type Luthier = {
  slug: string;
  name: string;
  city: string;
  country: string;
  site: string;
  contact: string;
  bio: string;
  address: string;
  phone: string;
  email: string;
  hours: string;
  craft: LuthierCraft;
  note: string;
};

function guitar(row: Omit<Luthier, "craft" | "note"> & Partial<Pick<Luthier, "note">>): Luthier {
  return { ...row, note: row.note ?? "", craft: "guitar" };
}

function bass(
  row: Omit<Luthier, "craft" | "contact" | "address" | "phone" | "email" | "hours" | "site" | "note"> &
    Partial<Pick<Luthier, "contact" | "address" | "phone" | "email" | "hours" | "site" | "note">>,
): Luthier {
  return {
    ...row,
    contact: row.contact ?? "",
    address: row.address ?? "",
    phone: row.phone ?? "",
    email: row.email ?? "",
    hours: row.hours ?? "By appointment",
    site: row.site ?? "",
    note: row.note ?? "",
    craft: "bass",
  };
}

function violin(
  row: Omit<Luthier, "craft" | "contact" | "address" | "phone" | "email" | "hours" | "site" | "note"> &
    Partial<Pick<Luthier, "contact" | "address" | "phone" | "email" | "hours" | "site" | "note">>,
): Luthier {
  return {
    ...row,
    contact: row.contact ?? "",
    address: row.address ?? "",
    phone: row.phone ?? "",
    email: row.email ?? "",
    hours: row.hours ?? "By appointment",
    site: row.site ?? "",
    note: row.note ?? "",
    craft: "violin",
  };
}

export function parseLuthierCraft(raw: string | undefined | null): LuthierCraft {
  if (raw === "bass") return "bass";
  if (raw === "violin") return "violin";
  return "guitar";
}

