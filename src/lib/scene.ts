export function collaboratorSlugs(slug: string): string[] {
  const found = new Set<string>();
  for (const [a, b] of PAIRS) {
    if (a === slug) found.add(b);
    if (b === slug) found.add(a);
  }
  for (const band of BANDS) {
    if (!band.members.includes(slug)) continue;
    for (const member of band.members) {
      if (member !== slug) found.add(member);
    }
  }
  return [...found];
}

export function bandsFor(slug: string): Band[] {
  return BANDS.filter((band) => band.members.includes(slug));
}

export function getBand(slug: string): Band | undefined {
  return BANDS.find((band) => band.slug === slug);
}

export function bandForBill(title: string): Band | undefined {
  const t = title.trim().toLowerCase();
  if (!t) return undefined;
  const exact = BANDS.find((band) => (band.name ?? "").toLowerCase() === t);
  if (exact) return exact;
  return BANDS.find((band) => {
    const n = (band.name ?? "").toLowerCase();
    if (!n) return false;
    return (
      t === `${n} trio` ||
      t === `${n} quartet` ||
      t === `${n} quintet` ||
      t === `${n} group` ||
      t.startsWith(`${n} +`) ||
      t.startsWith(`${n} &`) ||
      t.startsWith(`${n} —`) ||
      t.startsWith(`${n} -`)
    );
  });
}

export function leadSlug(band: Band): string {
  return band.members[0];
}

export function groupsForFestival(relatedSlugs: string[]): Band[] {
  return BANDS.filter((band) =>
    band.members.some((member) => relatedSlugs.includes(member)),
  );
}
